# ระดับ: แอดวานซ์ / ป้องกันข้อผิดพลาด
print("✨ โปรแกรมคำนวณพื้นที่แบบปลอดภัยสูง (Safe Calculator) ✨")

while True:
    try:
        # ดักจับกรณีผู้ใช้พิมพ์ใส่ข้อความที่ไม่ใช่ตัวเลข
        กว้าง = float(input("\nใส่ความกว้าง (หรือพิมพ์เลข 0 เพื่อออกจากโปรแกรม): "))
        if กว้าง == 0: 
            print("ขอบคุณที่ใช้งานโปรแกรมของเรา! บายยย 👋")
            break
            
        ยาว = float(input("ใส่ความยาว: "))
        
        # ดักจับกรณีใส่ค่าติดลบ ซึ่งในความเป็นจริงพื้นที่ติดลบไม่ได้
        if กว้าง <= 0 or ยาว <= 0:
            print("⚠️ ค่าความกว้างและยาวต้องมากกว่า 0 นะครับ ลองใหม่อีกครั้ง")
            continue
            
        พื้นที่ = กว้าง * ยาว
        print(f"✅ พื้นที่สี่เหลี่ยมของคุณคือ: {พื้นที่:.2f}")
        
    except ValueError:
        print("❌ ข้อผิดพลาด: กรุณากรอกเฉพาะ 'ตัวเลข' เท่านั้น ห้ามพิมพ์ตัวอักษร!")